const TEXT_EXTENSIONS = new Set([
  'txt',
  'md',
  'markdown',
  'csv',
  'json',
  'xml',
  'yaml',
  'yml',
  'js',
  'ts',
  'jsx',
  'tsx',
  'mjs',
  'py',
  'java',
  'c',
  'cpp',
  'h',
  'hpp',
  'cc',
  'html',
  'htm',
  'css',
  'scss',
  'sass',
  'less',
  'go',
  'rs',
  'rb',
  'php',
  'swift',
  'kt',
  'kts',
  'sql',
  'sh',
  'bash',
  'ps1',
  'zsh',
  'log',
  'conf',
  'ini',
  'env',
  'properties',
  'vue',
  'svelte',
  'svg'
])

export function isSupportedTextFile(filename: string): boolean {
  return TEXT_EXTENSIONS.has(filename.split('.').pop()?.toLowerCase() ?? '')
}
